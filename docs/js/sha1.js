// Pure-JS SHA-1 over a byte array.
//
// Deliberately not crypto.subtle: that API is async and requires a secure
// context, which would turn every keystroke into an async re-render and would
// break the page when opened directly from file://. SHA-1 is tiny and fast
// enough here that a synchronous implementation keeps the whole UUIDv5
// pipeline synchronous.
//
// SHA-1 is used because UUIDv5 is defined in terms of it (RFC 4122 S4.3). It is
// not used here for any security purpose.

function rotl(n, bits) {
  return ((n << bits) | (n >>> (32 - bits))) >>> 0;
}

/**
 * @param {Uint8Array} bytes
 * @returns {Uint8Array} the 20-byte digest
 */
export function sha1(bytes) {
  const bitLen = bytes.length * 8;

  // Pad: 0x80, then zeroes, then the 64-bit big-endian bit length.
  const padded = new Uint8Array((((bytes.length + 8) >> 6) + 1) << 6);
  padded.set(bytes);
  padded[bytes.length] = 0x80;

  // Length fits in the low 32 bits for any input this page can produce, but
  // write both halves so the implementation is correct in general.
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(bitLen / 0x100000000), false);
  view.setUint32(padded.length - 4, bitLen >>> 0, false);

  let h0 = 0x67452301;
  let h1 = 0xefcdab89;
  let h2 = 0x98badcfe;
  let h3 = 0x10325476;
  let h4 = 0xc3d2e1f0;

  const w = new Int32Array(80);

  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let i = 0; i < 16; i++) {
      w[i] = view.getInt32(offset + i * 4, false);
    }
    for (let i = 16; i < 80; i++) {
      w[i] = rotl(w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16], 1);
    }

    let a = h0;
    let b = h1;
    let c = h2;
    let d = h3;
    let e = h4;

    for (let i = 0; i < 80; i++) {
      let f;
      let k;
      if (i < 20) {
        f = (b & c) | (~b & d);
        k = 0x5a827999;
      } else if (i < 40) {
        f = b ^ c ^ d;
        k = 0x6ed9eba1;
      } else if (i < 60) {
        f = (b & c) | (b & d) | (c & d);
        k = 0x8f1bbcdc;
      } else {
        f = b ^ c ^ d;
        k = 0xca62c1d6;
      }

      const temp = (rotl(a, 5) + (f >>> 0) + e + k + (w[i] >>> 0)) >>> 0;
      e = d;
      d = c;
      c = rotl(b, 30);
      b = a;
      a = temp;
    }

    h0 = (h0 + a) >>> 0;
    h1 = (h1 + b) >>> 0;
    h2 = (h2 + c) >>> 0;
    h3 = (h3 + d) >>> 0;
    h4 = (h4 + e) >>> 0;
  }

  const out = new Uint8Array(20);
  const outView = new DataView(out.buffer);
  outView.setUint32(0, h0, false);
  outView.setUint32(4, h1, false);
  outView.setUint32(8, h2, false);
  outView.setUint32(12, h3, false);
  outView.setUint32(16, h4, false);
  return out;
}
